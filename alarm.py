"""
alarm.py - Plays a loud repeating beep while the driver is drowsy.

The alarm sound (sounds/alarm.wav) is generated by this file the first time,
so no sound file needs to be downloaded. Uses pygame for playback; on Windows
it falls back to the built-in winsound module if pygame is not available.
"""

import math
import os
import struct
import sys
import wave

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
SOUND_DIR = os.path.join(PROJECT_DIR, "sounds")
ALARM_PATH = os.path.join(SOUND_DIR, "alarm.wav")
CUE_PATH = os.path.join(SOUND_DIR, "cue_start.wav")
CUE_END_PATH = os.path.join(SOUND_DIR, "cue_end.wav")
WARN_PATH = os.path.join(SOUND_DIR, "warning.wav")
RATE = 44100


def _write_wav(path, segments, volume=0.8):
    """segments: list of (frequency_hz, seconds); frequency 0 = silence."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    frames = bytearray()
    for freq, secs in segments:
        n = int(RATE * secs)
        for i in range(n):
            if freq == 0:
                sample = 0.0
            else:
                # square-ish wave = harsh, attention-grabbing sound
                s = math.sin(2 * math.pi * freq * i / RATE)
                sample = volume * (1.0 if s >= 0 else -1.0) * 0.6 + volume * s * 0.4
                fade = min(1.0, i / 200, (n - i) / 200)   # avoid clicks
                sample *= fade
            frames += struct.pack("<h", int(max(-1, min(1, sample)) * 32767))
    with wave.open(path, "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(RATE)
        wf.writeframes(bytes(frames))


def ensure_sounds():
    if not os.path.exists(ALARM_PATH):
        # beep-beep pattern, about 1 second, played in a loop
        _write_wav(ALARM_PATH, [(1000, 0.18), (0, 0.06), (1400, 0.18), (0, 0.06),
                                (1000, 0.18), (0, 0.06), (1400, 0.18), (0, 0.10)])
    if not os.path.exists(CUE_PATH):
        # soft single "ding" used by evaluate.py to start/stop a trial
        _write_wav(CUE_PATH, [(880, 0.14), (0, 0.06), (1320, 0.22)], volume=0.75)   # high double ding
    if not os.path.exists(CUE_END_PATH):
        _write_wav(CUE_END_PATH, [(523, 0.35)], volume=0.75)                       # low ding
    if not os.path.exists(WARN_PATH):
        # gentle two-tone chime for the level-1 "you seem tired" warning
        _write_wav(WARN_PATH, [(880, 0.22), (0, 0.05), (660, 0.30)], volume=0.4)


class Alarm:
    def __init__(self, enabled=True):
        self.enabled = enabled
        self.playing = False
        self.backend = None
        ensure_sounds()
        try:
            os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
            import pygame
            pygame.mixer.init()
            self._pg_alarm = pygame.mixer.Sound(ALARM_PATH)
            self._pg_cue = pygame.mixer.Sound(CUE_PATH)
            self._pg_cue_end = pygame.mixer.Sound(CUE_END_PATH)
            self._pg_warn = pygame.mixer.Sound(WARN_PATH)
            self.backend = "pygame"
        except Exception:
            if sys.platform.startswith("win"):
                import winsound
                self._ws = winsound
                self.backend = "winsound"
            else:
                self.backend = "bell"
                print("[alarm] pygame not available - using terminal bell")

    def start(self):
        if not self.enabled or self.playing:
            return
        self.playing = True
        if self.backend == "pygame":
            self._pg_alarm.play(loops=-1)
        elif self.backend == "winsound":
            self._ws.PlaySound(ALARM_PATH, self._ws.SND_FILENAME |
                               self._ws.SND_ASYNC | self._ws.SND_LOOP)
        else:
            print("\a", end="", flush=True)

    def stop(self):
        if not self.playing:
            return
        self.playing = False
        if self.backend == "pygame":
            self._pg_alarm.stop()
        elif self.backend == "winsound":
            self._ws.PlaySound(None, 0)

    def cue(self, kind="start"):
        """Start / end signal for the accuracy test: a high double ding starts
        a trial, a low ding ends it (plays even when the alarm is muted)."""
        if self.backend == "pygame":
            (self._pg_cue if kind == "start" else self._pg_cue_end).play()
        elif self.backend == "winsound":
            self._ws.PlaySound(CUE_PATH if kind == "start" else CUE_END_PATH,
                               self._ws.SND_FILENAME | self._ws.SND_ASYNC)
        else:
            print("\a", end="", flush=True)

    def warn(self):
        """Gentle chime for an early fatigue warning (level 1 / 2)."""
        if not self.enabled or self.playing:
            return
        if self.backend == "pygame":
            self._pg_warn.play()
        elif self.backend == "winsound":
            self._ws.PlaySound(WARN_PATH, self._ws.SND_FILENAME | self._ws.SND_ASYNC)
        else:
            print("\a", end="", flush=True)

    def toggle_mute(self):
        if self.enabled:
            self.stop()
            self.enabled = False
        else:
            self.enabled = True
        return self.enabled
